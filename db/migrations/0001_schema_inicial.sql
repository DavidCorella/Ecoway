-- =====================================================================
-- Esquema inicial de EcoWay en PostgreSQL (migrado desde SQL Server 2022)
--
-- Equivalencias con el esquema anterior (db/schema, T-SQL):
--   UNIQUEIDENTIFIER + newid()    -> uuid + gen_random_uuid()
--   DATETIME + getdate()          -> timestamptz + now()  (todo en UTC)
--   DATE                          -> date
--   BIT                           -> boolean
--   DECIMAL(p,s)                  -> numeric(p,s)
--   VARCHAR/NVARCHAR(n)           -> varchar(n) COLLATE ci
--   VARCHAR/NVARCHAR(MAX)         -> text COLLATE ci
--   INT IDENTITY(1,1)             -> integer GENERATED BY DEFAULT AS IDENTITY
--
-- Los nombres de tablas y columnas van entre comillas con la misma grafia
-- que usa EF Core (Postgres distingue mayusculas en identificadores
-- entre comillas; SQL Server no).
-- =====================================================================

-- SQL Server comparaba texto sin distinguir mayusculas pero si tildes
-- (SQL_Latin1_General_CP1_CI_AS). Esta collation hace lo mismo:
-- 'Carton' = 'CARTON', pero 'Carton' <> 'Cartón'. Aplica a =, LIKE,
-- strpos (Contains de EF) y a los indices unicos
CREATE COLLATION IF NOT EXISTS ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

