-- ---------------------------------------------------------------------
-- Empresas
-- ---------------------------------------------------------------------
-- Las expresiones regulares no se pueden usar con una collation no
-- deterministica, por eso los CHECK comparan con COLLATE "C"
CREATE TABLE "Company" (
    "id"               uuid         NOT NULL DEFAULT gen_random_uuid(),
    "nombre_comercial" varchar(150) COLLATE ci NOT NULL,
    "razon_social"     varchar(150) COLLATE ci NOT NULL,
    "cedula_juridica"  varchar(30)  COLLATE ci NOT NULL,
    "address"          varchar(300) COLLATE ci NOT NULL,
    "contact_name"     varchar(150) COLLATE ci NOT NULL,
    "contact_id"       varchar(30)  COLLATE ci NOT NULL,
    "contact_position" varchar(100) COLLATE ci NOT NULL,
    "contact_phone"    varchar(30)  COLLATE ci NOT NULL,
    "contact_cell"     varchar(30)  COLLATE ci NOT NULL,
    "email"            varchar(150) COLLATE ci NOT NULL,
    "created_at"       timestamptz  NOT NULL DEFAULT now(),
    "project"          varchar(150) COLLATE ci NULL,
    "is_active"        boolean      NOT NULL DEFAULT true,
    -- Antes era columna calculada (isnull(project,'')), para que el indice
    -- unico trate "sin proyecto" como un valor y no deje repetir el nombre
    "project_key"      varchar(150) COLLATE ci GENERATED ALWAYS AS (coalesce("project", '')) STORED,
    CONSTRAINT "PK_Company" PRIMARY KEY ("id"),
    CONSTRAINT "CK_Company_CedulaJuridica" CHECK (("cedula_juridica" COLLATE "C") ~ '^[0-9]-[0-9]{3}-[0-9]{6}$'),
    CONSTRAINT "CK_Company_ContactCell" CHECK (("contact_cell" COLLATE "C") !~ '[^0-9]'),
    CONSTRAINT "CK_Company_ContactPhone" CHECK (("contact_phone" COLLATE "C") !~ '[^0-9]')
);
CREATE UNIQUE INDEX "UQ_Company_NombreProyecto" ON "Company" ("nombre_comercial", "project_key");
CREATE INDEX "IX_Company_is_active" ON "Company" ("is_active");

